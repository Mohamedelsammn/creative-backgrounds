import 'package:freezed_annotation/freezed_annotation.dart';

import '../../domain/entities/clock_config_entity.dart';

part 'clock_config_model.freezed.dart';
part 'clock_config_model.g.dart';

/// Persistence shape for [ClockConfigEntity] (Hive, and the JSON handed to the
/// native renderer over the clock channel).
///
/// The backend-authored fields are carried here too, so a saved configuration
/// round-trips everything the content team set rather than silently collapsing
/// to the subset the current UI exposes. Native `ClockConfig.kt` reads the keys
/// it knows and ignores the rest, so adding fields here is backwards
/// compatible with an older native build.
@freezed
class ClockConfigModel with _$ClockConfigModel {
  const ClockConfigModel._();

  const factory ClockConfigModel({
    @Default(ClockStyle.modern) ClockStyle style,
    @Default(ClockPosition.top) ClockPosition position,
    @Default(ClockFont.inter) ClockFont font,
    @Default(0xFFFFFFFF) int color,
    @Default(65.0) double sizePx,
    @Default(1.0) double opacity,
    @Default(true) bool showShadow,
    @Default(false) bool showGlow,
    @Default(false) bool showStroke,
    @Default(false) bool is24Hour,
    @Default(true) bool showDate,
    @Default(false) bool showSeconds,
    @Default(true) bool enabled,
    String? remoteStyle,
    String? remoteFont,
    @Default(400) int weight,
    @Default(1.0) double scale,
    @Default(0.0) double rotation,
    @Default(0.45) double depth,
    @Default(0.5) double shadowStrength,
    @Default(ClockDatePosition.below) ClockDatePosition datePosition,
    int? dateColor,
    double? customX,
    double? customY,
    @Default(1) int schemaVersion,
    @Default(1.0) double stretchY,
    @Default(1.0) double dateScale,
    @Default(ClockWeight.regular) ClockWeight fontWeightPreset,
    @Default(1.0) double horizontalScale,
    @Default(ClockTimeLayout.inline) ClockTimeLayout timeLayout,
    @Default(true) bool showColon,
    @Default(1.0) double lineSpacing,
    @Default(0.0) double minuteOffsetX,
    @Default(ClockColorMode.single) ClockColorMode colorMode,
    int? hoursColor,
    int? minutesColor,
    @Default(ClockColonColor.hours) ClockColonColor colonColor,
    int? colonColorCustom,
    @Default(2.0) double strokeWidth,
    @Default(false) bool showAmPm,
    int? gradientFrom,
    int? gradientTo,
    @Default(180.0) double gradientAngleDeg,
    @Default(1.0) double fillOpacity,
    String? hoursFont,
    String? minutesFont,
    @Default(0xFF000000) int strokeColor,
    @Default(ClockStrokeOrder.behind) ClockStrokeOrder strokeOrder,
    @Default(0.0) double fadeAmount,
    @Default(ClockFadeDirection.bottom) ClockFadeDirection fadeDirection,
    @Default(0.0) double blur,
    ClockHourFormat? hourFormat,
  }) = _ClockConfigModel;

  factory ClockConfigModel.fromJson(Map<String, dynamic> json) =>
      _$ClockConfigModelFromJson(json);

  factory ClockConfigModel.fromEntity(ClockConfigEntity e) => ClockConfigModel(
    style: e.style,
    position: e.position,
    font: e.font,
    color: e.color,
    sizePx: e.sizePx,
    opacity: e.opacity,
    showShadow: e.showShadow,
    showGlow: e.showGlow,
    showStroke: e.showStroke,
    is24Hour: e.is24Hour,
    showDate: e.showDate,
    showSeconds: e.showSeconds,
    enabled: e.enabled,
    remoteStyle: e.remoteStyle,
    remoteFont: e.remoteFont,
    weight: e.weight,
    scale: e.scale,
    rotation: e.rotation,
    depth: e.depth,
    shadowStrength: e.shadowStrength,
    datePosition: e.datePosition,
    dateColor: e.dateColor,
    customX: e.customX,
    customY: e.customY,
    schemaVersion: e.schemaVersion,
    stretchY: e.stretchY,
    dateScale: e.dateScale,
    fontWeightPreset: e.fontWeightPreset,
    horizontalScale: e.horizontalScale,
    timeLayout: e.timeLayout,
    showColon: e.showColon,
    lineSpacing: e.lineSpacing,
    minuteOffsetX: e.minuteOffsetX,
    colorMode: e.colorMode,
    hoursColor: e.hoursColor,
    minutesColor: e.minutesColor,
    colonColor: e.colonColor,
    colonColorCustom: e.colonColorCustom,
    strokeWidth: e.strokeWidth,
    showAmPm: e.showAmPm,
    gradientFrom: e.gradientFrom,
    gradientTo: e.gradientTo,
    gradientAngleDeg: e.gradientAngleDeg,
    fillOpacity: e.fillOpacity,
    hoursFont: e.hoursFont,
    minutesFont: e.minutesFont,
    strokeColor: e.strokeColor,
    strokeOrder: e.strokeOrder,
    fadeAmount: e.fadeAmount,
    fadeDirection: e.fadeDirection,
    blur: e.blur,
    hourFormat: e.hourFormat,
  );

  ClockConfigEntity toEntity() => ClockConfigEntity(
    style: style,
    position: position,
    font: font,
    color: color,
    sizePx: sizePx,
    opacity: opacity,
    showShadow: showShadow,
    showGlow: showGlow,
    showStroke: showStroke,
    is24Hour: is24Hour,
    showDate: showDate,
    showSeconds: showSeconds,
    enabled: enabled,
    remoteStyle: remoteStyle,
    remoteFont: remoteFont,
    weight: weight,
    scale: scale,
    rotation: rotation,
    depth: depth,
    shadowStrength: shadowStrength,
    datePosition: datePosition,
    dateColor: dateColor,
    customX: customX,
    customY: customY,
    schemaVersion: schemaVersion,
    stretchY: stretchY,
    dateScale: dateScale,
    fontWeightPreset: fontWeightPreset,
    horizontalScale: horizontalScale,
    timeLayout: timeLayout,
    showColon: showColon,
    lineSpacing: lineSpacing,
    minuteOffsetX: minuteOffsetX,
    colorMode: colorMode,
    hoursColor: hoursColor,
    minutesColor: minutesColor,
    colonColor: colonColor,
    colonColorCustom: colonColorCustom,
    strokeWidth: strokeWidth,
    showAmPm: showAmPm,
    gradientFrom: gradientFrom,
    gradientTo: gradientTo,
    gradientAngleDeg: gradientAngleDeg,
    fillOpacity: fillOpacity,
    hoursFont: hoursFont,
    minutesFont: minutesFont,
    strokeColor: strokeColor,
    strokeOrder: strokeOrder,
    fadeAmount: fadeAmount,
    fadeDirection: fadeDirection,
    blur: blur,
    hourFormat: hourFormat,
  );
}
